const seedDatabase = async () => {
  try {
    console.log('🌱 Seeding E-Products digital catalog across all 7 assessment categories...');

    for (const prod of sampleProducts) {
      await db.collection('products').doc(prod.id).set(prod, { merge: true });
    }
    console.log(`✅ Seeded ${sampleProducts.length} digital products across all 7 categories without duplicates.`);

    // 7 Official Digital Categories for the Technical Assessment
    const categoriesList = [
      'E-books',
      'Tutorials',
      'Study Materials',
      'Templates',
      'PDFs',
      'Design Resources',
      'Notes & Guides'
    ];

    for (const cat of categoriesList) {
      const catId = 'cat_' + cat.toLowerCase().replace(/[^a-z0-9]/g, '_');
      await db.collection('categories').doc(catId).set({
        id: catId,
        name: cat,
        isActive: true,
        updatedAt: new Date().toISOString()
      }, { merge: true });
    }
    console.log(`✅ Seeded ${categoriesList.length} digital categories into Cloud Firestore.`);

    console.log('🚀 Digital seeding completed successfully!');
    return { success: true, count: sampleProducts.length };
  } catch (error) {
    console.error('❌ Error during seeding:', error);
    throw error;
  }
};

// If executed directly from command line
if (require.main === module) {
  require('dotenv').config({ path: require('path').join(__dirname, '..', '.env') });
  seedDatabase()
    .then(() => process.exit(0))
    .catch((e) => {
      console.error(e);
      process.exit(1);
    });
}

